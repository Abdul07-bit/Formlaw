"""
Regenerate the documents that describe the implemented system, so they cannot drift from it:

    docs/openapi.json       OpenAPI schema of the running API
    docs/API_CONTRACTS.md   every endpoint (from the OpenAPI schema) + conventions
    docs/DATA_MODEL.md      every table, column, key and constraint (from the SQLAlchemy models)
    docs/DATA_SOURCES.md    the legal source registry and its review status (from legal-data/source-config/sources.json)

    backend/.venv/Scripts/python scripts/generate_docs.py        (Windows)   ·   backend/.venv/bin/python scripts/generate_docs.py
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
os.environ.setdefault("FORMLAW_ENV", "development")
os.environ.setdefault("JWT_SECRET", "docs-generation-only-" + "x" * 30)
sys.path.insert(0, str(ROOT / "backend"))

import app  # noqa: E402,F401
import app.models  # noqa: E402,F401
from sqlalchemy import CheckConstraint, ForeignKeyConstraint, UniqueConstraint  # noqa: E402

from app.db.base import Base  # noqa: E402
from app.ingestion import registry  # noqa: E402
from app.main import create_app  # noqa: E402

HEADER = "<!-- GENERATED by scripts/generate_docs.py — do not edit by hand -->\n\n"


def api_docs() -> None:
    spec = create_app().openapi()
    (DOCS / "openapi.json").write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    L = [HEADER + "# API contracts", "",
         f"FormLaw API **{spec['info']['version']}** · base path `/api/v1` · machine-readable schema: [openapi.json](openapi.json) "
         "(also served at `/api/docs` outside production).", "",
         "## Conventions", "",
         "* **Auth:** `Authorization: Bearer <access token>` (15 min). The refresh token is an httpOnly, SameSite=Strict cookie scoped "
         "to `/api/v1/auth`; cookie endpoints require `X-Requested-With: formlaw` (CSRF).",
         "* **Errors:** always `{\"error\": {\"code\", \"message\", \"request_id\", \"details?\"}}`. Resources the caller may not see return "
         "**404** (no existence oracle); a known resource with an action the role may not take returns **403**.",
         "* **Request ids:** every response carries `x-request-id` (send your own to correlate).",
         "* **Validation:** request bodies are camelCase and reject unknown fields (no mass assignment).",
         "* **High-risk actions** (external communication, sharing, deletion, client→advocate requests) create an approval that the "
         "responsible person must decide; the action is re-validated at execution.",
         "* **Connection features** (`/lawyers`, `/matching`, `/intakes/{id}/connect`, accepting requests) return "
         "`403 connection_feature_disabled` unless a compliance-reviewed ConnectionPolicy enables them.",
         "* **Known gap:** list endpoints are capped (e.g. 200–500 rows) rather than paginated; idempotency keys are not implemented.",
         "", "## Endpoints", "", "| Method | Path | Area | Summary |", "|---|---|---|---|"]
    for path, ops in sorted(spec["paths"].items()):
        for method, op in ops.items():
            summary = (op.get("summary") or op.get("operationId", "")).replace("|", "/")
            L.append(f"| {method.upper()} | `{path}` | {', '.join(op.get('tags', []))} | {summary} |")
    (DOCS / "API_CONTRACTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")


def data_model() -> None:
    L = [HEADER + "# Data model", "",
         "PostgreSQL in production (JSONB, tsvector GIN indexes, pgvector HNSW — added by migrations 0002/0005), SQLite in development. "
         "Schema changes are Alembic migrations in `database/migrations/versions`. Every case-scoped row carries `organization_id` "
         "and `case_id`; every repository query filters on both.", ""]
    for name in sorted(Base.metadata.tables):
        t = Base.metadata.tables[name]
        doc = (getattr(next((m.class_ for m in Base.registry.mappers if m.local_table is t), None), "__doc__", None) or "").strip()
        L += [f"## `{name}`", ""]
        if doc:
            L += [" ".join(doc.split()), ""]
        L += ["| Column | Type | Null | Key / default |", "|---|---|---|---|"]
        for c in t.columns:
            key = "PK" if c.primary_key else ", ".join(f"→ {fk.target_fullname}" for fk in c.foreign_keys)
            if c.unique:
                key += " unique"
            if c.index:
                key += " indexed"
            L.append(f"| `{c.name}` | {c.type} | {'yes' if c.nullable else 'no'} | {key.strip()} |")
        cons = [f"* CHECK `{c.name}`: `{c.sqltext}`" for c in t.constraints if isinstance(c, CheckConstraint)]
        cons += [f"* UNIQUE `{c.name or ''}` ({', '.join(col.name for col in c.columns)})" for c in t.constraints if isinstance(c, UniqueConstraint)]
        cons += [f"* FK ({', '.join(c.column_keys)}) ON DELETE {c.ondelete}" for c in t.constraints
                 if isinstance(c, ForeignKeyConstraint) and c.ondelete]
        if cons:
            L += [""] + cons
        L.append("")
    (DOCS / "DATA_MODEL.md").write_text("\n".join(L) + "\n", encoding="utf-8")


def data_sources() -> None:
    data = registry.load()
    start, end = registry.target_window(data)
    problems = registry.validate(data)
    L = [HEADER + "# Data sources", "",
         f"Registry: `legal-data/source-config/sources.json` (single source of truth). Target judgment window: **{start} → {end}**. "
         "Measured coverage: [CORPUS_COVERAGE.md](CORPUS_COVERAGE.md) (`python -m app.ingestion report`).", "",
         "Statuses: DISCOVERED (terms not reviewed) · UNDER_REVIEW · APPROVED · RESTRICTED (access controls or terms prevent automated "
         f"access — never bypassed) · REJECTED · EXPIRED_REVIEW (approved but reviewed more than {registry.REVIEW_VALID_DAYS} days ago). "
         "Only APPROVED sources are fetched. Approvals recorded here are engineering terms audits, **not legal opinions**.", "",
         f"Registry validation: {'OK' if not problems else '; '.join(problems)}", "",
         "| Source | Status | Authoritative | Licence / terms | Commercial use | Terms reviewed | Canonical URL |", "|---|---|---|---|---|---|---|"]
    for s in data["sources"]:
        L.append(f"| {s['name']} | {registry.effective_status(s)} | {'yes' if s.get('authoritative') else 'no (third-party copy)'} | "
                 f"{(s.get('license') or 'not reviewed').replace('|', '/')[:90]} | {s.get('commercial_use_allowed')} | {s.get('last_checked') or '—'} | "
                 f"{s['base_url']} |")
    L += ["", "## Decisions and known gaps", ""]
    for s in data["sources"]:
        L += [f"### {s['name']} — {registry.effective_status(s)}", "", s.get("decision_reason") or "—", ""]
        if s.get("robots_or_access_constraints"):
            L += [f"Access constraints: {s['robots_or_access_constraints']}", ""]
        L += [f"* {g}" for g in s.get("known_gaps") or []] + [""]
    (DOCS / "DATA_SOURCES.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    api_docs()
    data_model()
    data_sources()
    print("Wrote docs/openapi.json, API_CONTRACTS.md, DATA_MODEL.md, DATA_SOURCES.md")
